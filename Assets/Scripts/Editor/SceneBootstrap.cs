    /// <summary>
    /// Tools > Setup Main Scene. Creates placeholder materials, the zombie prefab, level assets and
    /// Assets/Scenes/Main.unity with everything wired up. Safe to re-run (assets are overwritten in place).
    /// </summary>
    public static class SceneBootstrap
    {
        const string ScenePath = "Assets/Scenes/Main.unity";
        const string MatDir = "Assets/Materials";
        const string PrefabDir = "Assets/Prefabs";
        const string VfxDir = "Assets/VFX";
        const string LevelDir = "Assets/Settings/Levels";

        [MenuItem("Tools/Setup Main Scene")]
        public static void Setup()
        {
            if (Resources.Load<TMP_Settings>("TMP Settings") == null)
            {
                EditorUtility.DisplayDialog("TextMeshPro resources needed",
                    "The TMP Essential Resources aren't imported yet. The importer window will open: click " +
                    "'Import TMP Essentials', then run Tools > Setup Main Scene again.", "OK");
                EditorApplication.ExecuteMenuItem("Window/TextMeshPro/Import TMP Essential Resources");
                return;
            }

            if (File.Exists(ScenePath) &&
                !EditorUtility.DisplayDialog("Overwrite Main scene?", ScenePath + " already exists. Rebuild it?", "Rebuild", "Cancel"))
                return;

            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo()) return;
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);

            EnsureFolders();
            Debug.Log($"[ZombieTD] Scifi kit: {KitMaterialConverter.ConvertFolder("Assets/Creepy_Cat")}");
            Mats mats = CreateMaterials();
            GameObject deathFx = CreateDeathEffect(mats);
            Zombie zombiePrefab = CreateZombiePrefab(mats, deathFx);
            LevelCatalog catalog = CreateLevels();
            CreateFireLightPrefab();
            ConfigureShadows();

            BuildScene(mats, zombiePrefab, catalog);

            EditorSceneManager.SaveScene(scene, ScenePath);
            AddSceneToBuildSettings(ScenePath);
            AssetDatabase.SaveAssets();
            Debug.Log("[ZombieTD] Main scene created. Press Play.");
        }

        // ---------------------------------------------------------------- folders

        static void EnsureFolders()
        {
            foreach (string dir in new[] { MatDir, PrefabDir, VfxDir, LevelDir, "Assets/Scenes", "Assets/Audio" })
            {
                if (AssetDatabase.IsValidFolder(dir)) continue;
                string parent = Path.GetDirectoryName(dir).Replace('\\', '/');
                AssetDatabase.CreateFolder(parent, Path.GetFileName(dir));
            }
        }

        // ---------------------------------------------------------------- materials

        class Mats
        {
            public Material wall, wallTop, ground, spawn, goal, gate, zombie, solidFx;
            public CityWallBuilder.Result city;
        }

        // Materials are only set up when first created, so textures/colours you assign later survive re-runs.
        static Mats CreateMaterials()
        {
            CityWallBuilder.Result city = CityWallBuilder.EnsureMaterials(false);
            var m = new Mats
            {
                city = city,
                wall = city.facades[0],   // ruined black glass towers (generated by CityWallBuilder)
                wallTop = city.roof,
                ground = Lit("Road", new Color(0.13f, 0.13f, 0.14f), 0.35f, 0f),         // wet-looking asphalt
                spawn = Lit("Spawn", new Color(0.45f, 0.08f, 0.08f), 0.2f, 0f),
                goal = Lit("Goal", new Color(0.28f, 0.17f, 0.09f), 0.3f, 0f),
                gate = Lit("GateSteel", new Color(0.16f, 0.17f, 0.19f), 0.55f, 0.85f),   // blast-door steel
                zombie = Lit("Zombie", new Color(0.35f, 0.55f, 0.25f), 0.2f, 0f),
                solidFx = LoadOrCreateMaterial("FX_Solid", "Universal Render Pipeline/Particles/Unlit", out _),
            };
            CreateBuildingGlassTemplate();
            return m;
        }

        static Material LoadOrCreateMaterial(string name, string shader, out bool created)
        {
            string path = $"{MatDir}/{name}.mat";
            var m = AssetDatabase.LoadAssetAtPath<Material>(path);
            created = m == null;
            if (created)
            {
                m = new Material(Shader.Find(shader));
                AssetDatabase.CreateAsset(m, path);
            }
            return m;
        }

        static Material Lit(string name, Color c, float smoothness, float metallic)
        {
            Material m = LoadOrCreateMaterial(name, "Universal Render Pipeline/Lit", out bool created);
            if (!created) return m;
            m.SetColor("_BaseColor", c);
            m.SetFloat("_Smoothness", smoothness);
            m.SetFloat("_Metallic", metallic);
            m.enableInstancing = true;
            EditorUtility.SetDirty(m);
            return m;
        }

        // Starting point for skyscraper glass: dark, glossy, with emission switched on. Put a window
        // texture in Emission Map (lit windows) and your glass texture in Base Map.
        static void CreateBuildingGlassTemplate()
        {
            Material m = LoadOrCreateMaterial("BuildingGlass_Template", "Universal Render Pipeline/Lit", out bool created);
            if (!created) return;
            m.SetColor("_BaseColor", new Color(0.05f, 0.07f, 0.1f));
            m.SetFloat("_Smoothness", 0.92f);
            m.SetFloat("_Metallic", 0.7f);
            m.EnableKeyword("_EMISSION");
            m.SetColor("_EmissionColor", new Color(0.55f, 0.65f, 0.9f) * 0.6f);
            m.globalIlluminationFlags = MaterialGlobalIlluminationFlags.RealtimeEmissive;
            m.enableInstancing = true;
            EditorUtility.SetDirty(m);
        }

        // Flickering orange point light to place next to fire effects.
        static void CreateFireLightPrefab()
        {
            string path = $"{PrefabDir}/FireLight.prefab";
            if (File.Exists(path)) return;
            var go = new GameObject("FireLight");
            Light l = go.AddComponent<Light>();
            l.type = LightType.Point;
            l.color = new Color(1f, 0.55f, 0.2f);
            l.range = 18f;
            l.intensity = 6f;
            l.shadows = LightShadows.None; // many fire lights + shadows gets expensive; enable on a few hero fires
            go.AddComponent<FireLight>();
            SavePrefab(go, path);
        }

        // ---------------------------------------------------------------- zombie

        // Gibs burst when a zombie dies.
        static GameObject CreateDeathEffect(Mats m)
        {
            var go = new GameObject("ZombieDeath");
            PooledVfx v = go.AddComponent<PooledVfx>();
            SetFloat(v, "lifetime", 1.2f);

            ParticleSystem ps = go.AddComponent<ParticleSystem>();
            ps.Stop(true, ParticleSystemStopBehavior.StopEmittingAndClear);

            ParticleSystem.MainModule main = ps.main;
            main.duration = 0.5f;
            main.loop = false;
            main.playOnAwake = false;
            main.startLifetime = new ParticleSystem.MinMaxCurve(0.4f, 0.8f);
            main.startSpeed = new ParticleSystem.MinMaxCurve(1.5f, 5f);
            main.startSize = new ParticleSystem.MinMaxCurve(0.1f, 0.22f);
            main.startColor = new ParticleSystem.MinMaxGradient(new Color(0.35f, 0.04f, 0.04f), new Color(0.25f, 0.4f, 0.15f));
            main.gravityModifier = 2.5f;
            main.simulationSpace = ParticleSystemSimulationSpace.World;
            main.maxParticles = 28;

            ParticleSystem.EmissionModule em = ps.emission;
            em.rateOverTime = 0f;
            em.SetBursts(new[] { new ParticleSystem.Burst(0f, (short)14) });

            ParticleSystem.ShapeModule sh = ps.shape;
            sh.shapeType = ParticleSystemShapeType.Sphere;
            sh.radius = 0.15f;

            ParticleSystem.SizeOverLifetimeModule sol = ps.sizeOverLifetime;
            sol.enabled = true;
            sol.size = new ParticleSystem.MinMaxCurve(1f, AnimationCurve.Linear(0f, 1f, 1f, 0f));

            var r = go.GetComponent<ParticleSystemRenderer>();
            r.sharedMaterial = m.solidFx;
            r.shadowCastingMode = ShadowCastingMode.Off;
            r.receiveShadows = false;

            return SavePrefab(go, $"{VfxDir}/ZombieDeath.prefab");
        }

        static Zombie CreateZombiePrefab(Mats m, GameObject deathFx)
        {
            GameObject z = GameObject.CreatePrimitive(PrimitiveType.Capsule);
            z.name = "Zombie";
            Object.DestroyImmediate(z.GetComponent<Collider>()); // no physics for horde members
            z.transform.localScale = new Vector3(0.4f, 0.45f, 0.4f); // 0.9 tall, pivot 0.45 above ground
            z.GetComponent<Renderer>().sharedMaterial = m.zombie;

            // Outstretched arms so facing reads from above.
            for (int side = -1; side <= 1; side += 2)
            {
                GameObject arm = GameObject.CreatePrimitive(PrimitiveType.Cube);
                arm.name = "Arm";
                Object.DestroyImmediate(arm.GetComponent<Collider>());
                arm.transform.SetParent(z.transform, false);
                arm.transform.localPosition = new Vector3(0.38f * side, 0.35f, 0.45f);
                arm.transform.localScale = new Vector3(0.22f, 0.2f, 0.75f);
                arm.GetComponent<Renderer>().sharedMaterial = m.zombie;
            }
            SetLayer(z, "Zombie");

            Zombie zombie = z.AddComponent<Zombie>();
            SetRef(zombie, "deathVfx", deathFx);
            return SavePrefab(z, $"{PrefabDir}/Zombie.prefab").GetComponent<Zombie>();
        }

        // ---------------------------------------------------------------- levels

        // Level assets are only filled in when first created, so your tweaks survive re-runs.
        static LevelCatalog CreateLevels()
        {
            // Level 1 (intro): a road between the base's defensive walls; spawn right, base gate left.
            // LevelData's defaults already describe this level.
            LevelData gate = LoadOrCreate<LevelData>($"{LevelDir}/Level01_TheGate.asset", out bool newGate);
            if (newGate)
            {
                gate.displayName = "The Gate";
                gate.layout = LevelLayout.Corridor;
                EditorUtility.SetDirty(gate);
            }

            // Level 2: a maze. Narrow 1-tile roads need shorter walls and a steeper camera to stay readable.
            LevelData maze = LoadOrCreate<LevelData>($"{LevelDir}/Level02_Labyrinth.asset", out bool newMaze);
            if (newMaze)
            {
                maze.displayName = "The Labyrinth";
                maze.layout = LevelLayout.RandomMaze;
                maze.wallHeight = 8f;
                maze.mazeWidth = 31;
                maze.mazeHeight = 31;
                maze.cameraPitch = 75f;
                maze.cameraStartDistance = 120f;
                maze.cameraMinDistance = 30f;
                maze.cameraMaxDistance = 220f;
                EditorUtility.SetDirty(maze);
            }

            LevelCatalog catalog = LoadOrCreate<LevelCatalog>("Assets/Settings/LevelCatalog.asset", out bool newCatalog);
            if (newCatalog || catalog.Count == 0)
            {
                catalog.levels = new[] { gate, maze };
                EditorUtility.SetDirty(catalog);
            }
            return catalog;
        }

        static T LoadOrCreate<T>(string path, out bool created) where T : ScriptableObject
        {
            var asset = AssetDatabase.LoadAssetAtPath<T>(path);
            created = asset == null;
            if (!created) return asset;
            asset = ScriptableObject.CreateInstance<T>();
            AssetDatabase.CreateAsset(asset, path);
            return asset;
        }

        // The camera sits 100+ units up, so the default shadow distance would cut off the wall shadows.
        static void ConfigureShadows()
        {
            if (GraphicsSettings.currentRenderPipeline is UniversalRenderPipelineAsset urp && urp.shadowDistance < 400f)
            {
                urp.shadowDistance = 400f;
                EditorUtility.SetDirty(urp);
            }
        }

        // ---------------------------------------------------------------- scene

        static void BuildScene(Mats m, Zombie zombiePrefab, LevelCatalog catalog)
        {
            // Lighting is applied at the end (LightingPresets: Day for now, Night via Tools > Lighting > Night).
            CreatePostProcessing();

            // Level.
            var levelGo = new GameObject("Level");
            LevelGenerator level = levelGo.AddComponent<LevelGenerator>();
            SetRef(level, "catalog", catalog);
            CityWallBuilder.Apply(level, m.city); // facade variants + roof
            Material floor = RoadFloorSetup.EnsureMaterial(); // null if the kit isn't imported
            if (floor != null) RoadFloorSetup.Apply(level, floor);
            SetRef(level, "groundMaterial", m.ground);
            SetRef(level, "spawnMaterial", m.spawn);
            SetRef(level, "goalMaterial", m.goal);
            SetRef(level, "gateMaterial", m.gate);

            // Camera rig (CameraRig re-centres on the level at runtime).
            var rig = new GameObject("CameraRig");
            var camGo = new GameObject("Main Camera") { tag = "MainCamera" };
            camGo.transform.SetParent(rig.transform, false);
            Camera cam = camGo.AddComponent<Camera>();
            cam.fieldOfView = 40f;
            cam.nearClipPlane = 0.5f;
            cam.farClipPlane = 1000f;
            cam.clearFlags = CameraClearFlags.SolidColor;
            camGo.AddComponent<AudioListener>();
            cam.GetUniversalAdditionalCameraData().renderPostProcessing = true;
            camGo.transform.position = Quaternion.Euler(62f, 0f, 0f) * Vector3.back * 120f;
            camGo.transform.rotation = Quaternion.Euler(62f, 0f, 0f);
            CameraRig cameraRig = rig.AddComponent<CameraRig>();
            SetRef(cameraRig, "cam", cam);
            SetRef(cameraRig, "level", level);

            // Gameplay systems.
            var systems = new GameObject("GameSystems");
            systems.AddComponent<PoolManager>();
            systems.AddComponent<GameManager>();
            ZombieManager zm = systems.AddComponent<ZombieManager>();
            SetRef(zm, "level", level);
            WaveSpawner spawner = systems.AddComponent<WaveSpawner>();
            SetRef(spawner, "level", level);
            SetRef(spawner, "zombies", zm);
            SetRef(spawner, "zombiePrefab", zombiePrefab);

            BuildUi(spawner, zm);
            LightingPresets.Apply(LightingPreset.Day); // creates the Sun, sets ambient/fog/camera colours
        }

        static void CreatePostProcessing()
        {
            // Night grade: strong bloom so fires, windows and muzzle flashes glow; cool, slightly desaturated.
            string path = "Assets/Settings/NightVolumeProfile.asset";
            var profile = AssetDatabase.LoadAssetAtPath<VolumeProfile>(path);
            if (profile == null)
            {
                profile = ScriptableObject.CreateInstance<VolumeProfile>();
                AssetDatabase.CreateAsset(profile, path);

                Bloom bloom = profile.Add<Bloom>(true);
                bloom.threshold.Override(0.9f);
                bloom.intensity.Override(1.6f);
                bloom.scatter.Override(0.7f);
                Tonemapping tone = profile.Add<Tonemapping>(true);
                tone.mode.Override(TonemappingMode.ACES);
                ColorAdjustments color = profile.Add<ColorAdjustments>(true);
                color.postExposure.Override(0.3f);
                color.contrast.Override(15f);
                color.saturation.Override(-12f);
                WhiteBalance white = profile.Add<WhiteBalance>(true);
                white.temperature.Override(-15f); // cooler night tint; fire stays warm by contrast
                Vignette vignette = profile.Add<Vignette>(true);
                vignette.intensity.Override(0.35f);
                foreach (VolumeComponent c in profile.components) AssetDatabase.AddObjectToAsset(c, profile);
                EditorUtility.SetDirty(profile);
            }

            var go = new GameObject("PostProcessVolume");
            Volume v = go.AddComponent<Volume>();
            v.isGlobal = true;
            v.sharedProfile = profile;
        }

        static void BuildUi(WaveSpawner spawner, ZombieManager zm)
        {
            var canvasGo = new GameObject("HUD", typeof(RectTransform));
            Canvas canvas = canvasGo.AddComponent<Canvas>();
            canvas.renderMode = RenderMode.ScreenSpaceOverlay;
            CanvasScaler scaler = canvasGo.AddComponent<CanvasScaler>();
            scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
            scaler.referenceResolution = new Vector2(1920, 1080);
            scaler.matchWidthOrHeight = 0.5f;
            canvasGo.AddComponent<GraphicRaycaster>();

            new GameObject("EventSystem", typeof(EventSystem), typeof(InputSystemUIInputModule));

            Transform root = canvasGo.transform;
            var topLeft = new Vector2(0, 1);
            TMP_Text health = Text(root, "Health", topLeft, new Vector2(30, -25), new Vector2(500, 50), 34, TextAlignmentOptions.TopLeft);
            TMP_Text money = Text(root, "Money", topLeft, new Vector2(30, -70), new Vector2(500, 50), 34, TextAlignmentOptions.TopLeft);
            TMP_Text alive = Text(root, "Zombies", topLeft, new Vector2(30, -115), new Vector2(500, 50), 28, TextAlignmentOptions.TopLeft);
            money.color = new Color(1f, 0.85f, 0.3f);

            TMP_Text wave = Text(root, "Wave", new Vector2(0.5f, 1), new Vector2(0, -25), new Vector2(1200, 50), 34, TextAlignmentOptions.Top);

            TMP_Text message = Text(root, "Message", new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(1400, 300), 90, TextAlignmentOptions.Center);
            message.color = new Color(1f, 0.35f, 0.25f);

            HudController hud = canvasGo.AddComponent<HudController>();
            SetRef(hud, "healthText", health);
            SetRef(hud, "moneyText", money);
            SetRef(hud, "waveText", wave);
            SetRef(hud, "zombiesText", alive);
            SetRef(hud, "messageText", message);
            SetRef(hud, "spawner", spawner);
            SetRef(hud, "zombies", zm);
        }

        // Anchored text box; pivot matches the anchor so positions read naturally.
        static TMP_Text Text(Transform parent, string name, Vector2 anchor, Vector2 pos, Vector2 size,
            float fontSize, TextAlignmentOptions align)
        {
            var go = new GameObject(name, typeof(RectTransform));
            var rt = (RectTransform)go.transform;
            rt.SetParent(parent, false);
            rt.anchorMin = rt.anchorMax = rt.pivot = anchor;
            rt.anchoredPosition = pos;
            rt.sizeDelta = size;
            TextMeshProUGUI t = go.AddComponent<TextMeshProUGUI>();
            t.fontSize = fontSize;
            t.alignment = align;
            t.fontStyle = FontStyles.Bold;
            t.color = Color.white;
            t.raycastTarget = false;
            t.textWrappingMode = TextWrappingModes.NoWrap;
            return t;
        }

        static void AddSceneToBuildSettings(string path)
        {
            var scenes = new List<EditorBuildSettingsScene>(EditorBuildSettings.scenes);
            scenes.RemoveAll(s => s.path == path);
            scenes.Insert(0, new EditorBuildSettingsScene(path, true));
            EditorBuildSettings.scenes = scenes.ToArray();
        }

        // ---------------------------------------------------------------- helpers

        static GameObject SavePrefab(GameObject go, string path)
        {
            GameObject asset = PrefabUtility.SaveAsPrefabAsset(go, path);
            Object.DestroyImmediate(go);
            return asset;
        }

        static void SetLayer(GameObject go, string layerName)
        {
            int layer = LayerMask.NameToLayer(layerName);
            if (layer < 0) return;
            foreach (Transform t in go.GetComponentsInChildren<Transform>(true)) t.gameObject.layer = layer;
        }

        static SerializedProperty Prop(SerializedObject so, string name)
        {
            SerializedProperty p = so.FindProperty(name);
            if (p == null) Debug.LogError($"[ZombieTD] Field '{name}' not found on {so.targetObject.GetType().Name}");
            return p;
        }

        static void SetRef(Object target, string field, Object value)
        {
            var so = new SerializedObject(target);
            SerializedProperty p = Prop(so, field);
            if (p == null) return;
            p.objectReferenceValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        static void SetFloat(Object target, string field, float value)
        {
            var so = new SerializedObject(target);
            SerializedProperty p = Prop(so, field);
            if (p == null) return;
            p.floatValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }
    }
